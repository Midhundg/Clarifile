"""Modular LLM service with Google Gemini API integration and testing mocks."""

from abc import ABC, abstractmethod
from typing import Optional
from google import genai
from google.genai import types
from google.genai.errors import APIError

from utils.config import Config


class LLMError(Exception):
    """Base exception for LLM operations."""
    pass


class MissingAPIKeyError(LLMError):
    """Raised when an API key is required but missing or unconfigured."""
    pass


class RateLimitError(LLMError):
    """Raised when the LLM provider rate limit or quota is exceeded."""
    pass


class BaseLLMService(ABC):
    """Abstract base class for LLM providers."""

    @abstractmethod
    def generate(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        temperature: float = 0.2,
    ) -> str:
        """Generate text from the LLM given a prompt and optional system instruction."""
        pass


class GeminiLLMService(BaseLLMService):
    """Google Gemini API LLM service implementation using the official google-genai SDK."""

    def __init__(
        self,
        api_key: Optional[str] = None,
        model: Optional[str] = None,
    ):
        self.api_key = Config.get_gemini_api_key(api_key)
        self.model = model or Config.GEMINI_MODEL
        self._client: Optional[genai.Client] = None

    def _get_client(self) -> genai.Client:
        """Lazily initialize and validate the Gemini Client."""
        if not self.api_key or len(self.api_key) < 5:
            raise MissingAPIKeyError(
                "Gemini API key is not configured. Please enter your API key in the sidebar "
                "or set GEMINI_API_KEY in your .env file."
            )
        if self._client is None:
            self._client = genai.Client(api_key=self.api_key)
        return self._client

    def generate(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        temperature: float = 0.2,
    ) -> str:
        """Generate content via the Gemini API with automatic model fallback."""
        client = self._get_client()
        sys_instruction = system_instruction or Config.SYSTEM_INSTRUCTION

        # Candidate models to try in case of model deprecation / 404
        models_to_try = [self.model]
        for fallback in ["gemini-3.8-flash", "gemini-3.5-flash", "gemini-flash-latest"]:
            if fallback not in models_to_try:
                models_to_try.append(fallback)

        last_error = None
        for candidate_model in models_to_try:
            try:
                config = types.GenerateContentConfig(
                    system_instruction=sys_instruction,
                    temperature=temperature,
                )
                response = client.models.generate_content(
                    model=candidate_model,
                    contents=prompt,
                    config=config,
                )

                if response.text:
                    self.model = candidate_model  # Remember working model
                    return response.text.strip()
                return "No content was generated by the model."

            except APIError as e:
                err_str = str(e)
                # If model is 404 / deprecated, try next fallback model
                if "404" in err_str or "NOT_FOUND" in err_str:
                    last_error = e
                    continue
                if "429" in err_str or "RESOURCE_EXHAUSTED" in err_str.upper():
                    raise RateLimitError("Gemini API rate limit or quota exceeded. Please try again shortly.") from e
                raise LLMError(f"Gemini API error: {err_str}") from e
            except MissingAPIKeyError:
                raise
            except Exception as e:
                raise LLMError(f"LLM generation failed: {str(e)}") from e

        if last_error:
            raise LLMError(f"Gemini API error: {str(last_error)}") from last_error


class MockLLMService(BaseLLMService):
    """Mock LLM provider for offline testing and verification without API usage."""

    def __init__(self, default_response: Optional[str] = None):
        self.default_response = default_response
        self.call_history = []

    def generate(
        self,
        prompt: str,
        system_instruction: Optional[str] = None,
        temperature: float = 0.2,
    ) -> str:
        self.call_history.append({"prompt": prompt, "system_instruction": system_instruction})

        if self.default_response:
            return self.default_response

        # Grounded mock response reflecting prompt contents
        if "summary" in prompt.lower():
            return "Mock Summary: This document covers key topics including systems architecture and data workflows."
        if "compare" in prompt.lower():
            return "Mock Comparison: Document A focuses on implementation, while Document B focuses on validation."
        if "key point" in prompt.lower():
            return "1. Main finding from document.\n2. Decision on operational strategy.\n3. Implementation milestone."

        return "This is a grounded mock response based on the retrieved context passages."


def get_llm_service(
    api_key: Optional[str] = None,
    use_mock: bool = False,
    mock_response: Optional[str] = None,
) -> BaseLLMService:
    """Factory helper to obtain the configured LLM service instance."""
    if use_mock:
        return MockLLMService(default_response=mock_response)
    return GeminiLLMService(api_key=api_key)
